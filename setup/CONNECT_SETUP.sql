-- Apply ONLY after deploying the new web app and setting server-side environment variables.
-- Retain profile tombstones so conversations/messages continue to reference existing IDs.
ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_id_fkey;
-- Deleted profiles must remain visible for history, but must not appear in contact directory.
DROP POLICY IF EXISTS "members see active profiles" ON public.profiles;
CREATE POLICY "members see active profiles" ON public.profiles FOR SELECT TO authenticated
USING (true);

CREATE TABLE IF NOT EXISTS public.connect_sticker_packs (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
 emoji text NOT NULL DEFAULT '🎨',
 is_public boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.connect_stickers (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 pack_id uuid NOT NULL REFERENCES public.connect_sticker_packs(id) ON DELETE CASCADE,
 name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
 storage_path text NOT NULL UNIQUE,
 position int NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.connect_sticker_packs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.connect_stickers ENABLE ROW LEVEL SECURITY;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.connect_sticker_packs,public.connect_stickers TO authenticated;
DROP POLICY IF EXISTS "read visible packs" ON public.connect_sticker_packs;
CREATE POLICY "read visible packs" ON public.connect_sticker_packs FOR SELECT TO authenticated USING (is_public OR owner_id=(select auth.uid()));
DROP POLICY IF EXISTS "create own packs" ON public.connect_sticker_packs;
CREATE POLICY "create own packs" ON public.connect_sticker_packs FOR INSERT TO authenticated WITH CHECK (owner_id=(select auth.uid()));
DROP POLICY IF EXISTS "edit own packs" ON public.connect_sticker_packs;
CREATE POLICY "edit own packs" ON public.connect_sticker_packs FOR UPDATE TO authenticated USING (owner_id=(select auth.uid())) WITH CHECK (owner_id=(select auth.uid()));
DROP POLICY IF EXISTS "delete own packs" ON public.connect_sticker_packs;
CREATE POLICY "delete own packs" ON public.connect_sticker_packs FOR DELETE TO authenticated USING (owner_id=(select auth.uid()));
DROP POLICY IF EXISTS "read visible stickers" ON public.connect_stickers;
CREATE POLICY "read visible stickers" ON public.connect_stickers FOR SELECT TO authenticated USING (EXISTS (SELECT 1 FROM public.connect_sticker_packs p WHERE p.id=pack_id AND (p.is_public OR p.owner_id=(select auth.uid()))));
DROP POLICY IF EXISTS "create own stickers" ON public.connect_stickers;
CREATE POLICY "create own stickers" ON public.connect_stickers FOR INSERT TO authenticated WITH CHECK (EXISTS (SELECT 1 FROM public.connect_sticker_packs p WHERE p.id=pack_id AND p.owner_id=(select auth.uid()) AND storage_path LIKE (select auth.uid())::text || '/' || pack_id::text || '/%'));
DROP POLICY IF EXISTS "delete own stickers" ON public.connect_stickers;
CREATE POLICY "delete own stickers" ON public.connect_stickers FOR DELETE TO authenticated USING (EXISTS (SELECT 1 FROM public.connect_sticker_packs p WHERE p.id=pack_id AND p.owner_id=(select auth.uid())));
-- Private sticker images must not be public; signed URLs are generated by authenticated users.
INSERT INTO storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
VALUES ('connect-stickers','connect-stickers',false,2097152,ARRAY['image/png','image/webp','image/gif'])
ON CONFLICT (id) DO NOTHING;
DROP POLICY IF EXISTS "upload own sticker assets" ON storage.objects;
CREATE POLICY "upload own sticker assets" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id='connect-stickers' AND (storage.foldername(name))[1]=(select auth.uid())::text);
DROP POLICY IF EXISTS "read sticker assets" ON storage.objects;
CREATE POLICY "read sticker assets" ON storage.objects FOR SELECT TO authenticated USING (bucket_id='connect-stickers' AND EXISTS (SELECT 1 FROM public.connect_stickers s JOIN public.connect_sticker_packs p ON p.id=s.pack_id WHERE s.storage_path=name AND (p.is_public OR p.owner_id=(select auth.uid()))));
DROP POLICY IF EXISTS "delete own sticker assets" ON storage.objects;
CREATE POLICY "delete own sticker assets" ON storage.objects FOR DELETE TO authenticated USING (bucket_id='connect-stickers' AND (storage.foldername(name))[1]=(select auth.uid())::text);
